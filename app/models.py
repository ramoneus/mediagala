"""SQLAlchemy ORM models."""

import enum
from datetime import datetime

from sqlalchemy import CheckConstraint, DateTime, Enum, ForeignKey, String, Text, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.catalog import Completion, Kind, Status
from app.database import Base

Episode = tuple[int, int]  # (season number, episode number), both starting at 1


def _str_enum(enum_cls: type[enum.StrEnum]) -> Enum:
    # Store the readable value ("watched") rather than the member name ("WATCHED").
    return Enum(enum_cls, native_enum=False, length=20, values_callable=lambda e: [m.value for m in e])


class Title(Base):
    """A movie, series or game. All share one table, so search, filters and sorting work for every kind."""

    __tablename__ = "titles"
    __table_args__ = (
        CheckConstraint("rating IS NULL OR rating BETWEEN 1 AND 10", name="ck_titles_rating_range"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    kind: Mapped[Kind] = mapped_column(_str_enum(Kind), default=Kind.MOVIE, index=True)
    title: Mapped[str] = mapped_column(String(200), index=True)
    year: Mapped[int]
    genre: Mapped[str] = mapped_column(String(50), index=True)
    description: Mapped[str] = mapped_column(Text, default="")
    rating: Mapped[int | None]
    # Name of an uploaded image inside data/posters/ (generated by us, never the user's file name).
    poster_filename: Mapped[str | None] = mapped_column(String(100))
    status: Mapped[Status] = mapped_column(_str_enum(Status), default=Status.PLANNED, index=True)
    # Series only: the last episode watched. Episodes are watched in order,
    # so one "bookmark" is enough to know everything before it is watched too.
    progress_season: Mapped[int | None]
    progress_episode: Mapped[int | None]
    # Games only.
    completion: Mapped[Completion | None] = mapped_column(_str_enum(Completion))
    hours_played: Mapped[int | None]
    # Books only.
    author: Mapped[str] = mapped_column(String(200), default="")
    pages: Mapped[int | None]
    current_page: Mapped[int | None]
    created_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now(), onupdate=func.now())

    seasons: Mapped[list["Season"]] = relationship(
        back_populates="series",
        order_by="Season.number",
        cascade="all, delete-orphan",
        lazy="selectin",  # load all seasons of a page of titles in one extra query
    )

    def __repr__(self) -> str:
        return f"<Title id={self.id} kind={self.kind} title={self.title!r}>"

    @property
    def reading_percent(self) -> int:
        if not self.pages or self.current_page is None:
            return 0
        return min(100, round(100 * self.current_page / self.pages))

    @property
    def status_label(self) -> str:
        """The status as this kind calls it, e.g. "Completed" for a finished game."""
        return self.kind.config.status_labels.get(self.status, self.status.value.capitalize())

    # --- Episode progress (series only). Seasons are always numbered 1..n. ---

    @property
    def progress(self) -> Episode | None:
        if self.progress_season is None or self.progress_episode is None:
            return None
        return (self.progress_season, self.progress_episode)

    @property
    def total_episodes(self) -> int:
        return sum(season.episode_count for season in self.seasons)

    @property
    def watched_episodes(self) -> int:
        if self.progress is None:
            return 0
        earlier = sum(s.episode_count for s in self.seasons if s.number < self.progress_season)
        return earlier + self.progress_episode

    @property
    def progress_percent(self) -> int:
        total = self.total_episodes
        return round(100 * self.watched_episodes / total) if total else 0

    @property
    def next_episode(self) -> Episode | None:
        """The first unwatched episode, or None when every episode has been watched."""
        if not self.seasons:
            return None
        if self.progress is None:
            return (1, 1)
        season, episode = self.progress
        if episode < self.seasons[season - 1].episode_count:
            return (season, episode + 1)
        if season < len(self.seasons):
            return (season + 1, 1)
        return None

    def has_episode(self, season: int, episode: int) -> bool:
        return 1 <= season <= len(self.seasons) and 1 <= episode <= self.seasons[season - 1].episode_count

    def episode_before(self, season: int, episode: int) -> Episode | None:
        if episode > 1:
            return (season, episode - 1)
        if season > 1:
            return (season - 1, self.seasons[season - 2].episode_count)
        return None

    def is_episode_watched(self, season: int, episode: int) -> bool:
        return self.progress is not None and (season, episode) <= self.progress

    def watched_in_season(self, season: int) -> int:
        if self.progress is None or season > self.progress_season:
            return 0
        if season < self.progress_season:
            return self.seasons[season - 1].episode_count
        return self.progress_episode


class Season(Base):
    __tablename__ = "seasons"
    __table_args__ = (
        UniqueConstraint("title_id", "number", name="uq_seasons_title_number"),
        CheckConstraint("episode_count BETWEEN 1 AND 500", name="ck_seasons_episode_count"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    title_id: Mapped[int] = mapped_column(ForeignKey("titles.id", ondelete="CASCADE"), index=True)
    number: Mapped[int]
    episode_count: Mapped[int]

    series: Mapped[Title] = relationship(back_populates="seasons")
